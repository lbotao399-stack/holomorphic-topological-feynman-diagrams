"""Dimensions of invariant subspaces, two methods.

(W) Weyl character formula: mult of the trivial representation in V = sum_{w in W} sgn(w) m_V(rho - w rho),
    m_V = weight multiplicities (exact counting from the weights of the basis), W generated by the simple
    reflections of the root system read off from the weights (exact rationals; inner product on h* from kappa|h),
    sgn(w) = (-1)^{#{alpha > 0 : (w rho, alpha) < 0}}.
(L) Linear algebra: unknown symmetric / alternating tensors on h-weight-zero index sets, invariance under every
    basis element; rank modulo two primes (lower bound of the rational rank, so nullity mod p >= nullity over Q
    is an upper bound for the dimension); lower bound from explicit invariants.
"""
import itertools
import numpy as np
import sympy as sp
from fractions import Fraction as Fr


def root_data(L):
    kh = sp.Matrix([[int(L.kappa[a, b]) for b in L.cartan] for a in L.cartan])
    khinv = [[Fr(int(sp.Rational(x).p), int(sp.Rational(x).q)) for x in row] for row in kh.inv().tolist()]
    r = len(L.cartan)
    def ip(x, y):
        return sum(Fr(x[i]) * khinv[i][j] * Fr(y[j]) for i in range(r) for j in range(r))
    roots = sorted({w for w in L.wt if any(w)})
    gen = [1000003 ** i for i in range(r)][::-1]
    val = lambda w: sum(x * g for x, g in zip(w, gen))
    pos = [w for w in roots if val(w) > 0]
    possum = {tuple(a + b for a, b in zip(x, y)) for x in pos for y in pos}
    simple = [w for w in pos if w not in possum]
    assert len(simple) == r
    return ip, roots, pos, simple


def weyl_orbit_rho(L):
    ip, roots, pos, simple = root_data(L)
    rho = tuple(Fr(sum(w[k] for w in pos), 2) for k in range(len(L.cartan)))
    refl = []
    for a in simple:
        aa = ip(a, a)
        refl.append((a, aa))
    def s(i, lam):
        a, aa = refl[i]
        c = 2 * ip(lam, a) / aa
        return tuple(x - c * y for x, y in zip(lam, a))
    orbit = {rho}
    frontier = [rho]
    while frontier:
        new = []
        for lam in frontier:
            for i in range(len(simple)):
                m = s(i, lam)
                if m not in orbit:
                    orbit.add(m); new.append(m)
        frontier = new
    out = []
    for lam in orbit:
        neg = sum(1 for a in pos if ip(lam, a) < 0)
        mu = tuple(r_ - l_ for r_, l_ in zip(rho, lam))
        assert all(x.denominator == 1 for x in mu)
        out.append((tuple(int(x) for x in mu), (-1) ** neg))
    return out, len(pos)


def weight_mults(L, k, kind):
    """dict weight -> multiplicity in S^k g ('S'), Lambda^k g ('L') or g^{(x)k} ('T')."""
    wts = [tuple(int(x) for x in w) for w in L.wt]
    add = lambda x, y: tuple(a + b for a, b in zip(x, y))
    zero = tuple(0 for _ in L.cartan)
    if kind == 'T':
        cur = {zero: 1}
        base = {}
        for w in wts:
            base[w] = base.get(w, 0) + 1
        for _ in range(k):
            nxt = {}
            for x, m in cur.items():
                for y, n in base.items():
                    z = add(x, y); nxt[z] = nxt.get(z, 0) + m * n
            cur = nxt
        return cur
    # dp over basis elements: dp[j] = dict weight -> count of j-multisets / j-subsets
    dp = [dict() for _ in range(k + 1)]
    dp[0][zero] = 1
    for w in wts:
        new = [dict(x) for x in dp]
        maxmult = k if kind == 'S' else 1
        for j in range(k + 1):
            for x, m in dp[j].items():
                y = x
                for t in range(1, maxmult + 1):
                    if j + t > k:
                        break
                    y = add(y, w)
                    new[j + t][y] = new[j + t].get(y, 0) + m
        dp = new
    return dp[k]


def invariant_dims(L, specs):
    orb, npos = weyl_orbit_rho(L)
    out = {}
    for k, kind in specs:
        m = weight_mults(L, k, kind)
        out[(k, kind)] = sum(sg * m.get(mu, 0) for mu, sg in orb)
    return out, len(orb)


# ----------------------------------------------------------------------------- (L) linear algebra
def rank_mod(rows, ncol, p):
    """rank of a sparse integer matrix (list of dict col->val) modulo p."""
    piv = {}
    r = 0
    for row in rows:
        v = {c: x % p for c, x in row.items() if x % p}
        while v:
            c = min(v)
            if c in piv:
                pr = piv[c]
                f = v[c]
                for cc, x in pr.items():
                    v[cc] = (v.get(cc, 0) - f * x) % p
                    if v[cc] == 0:
                        del v[cc]
            else:
                inv = pow(v[c], p - 2, p)
                v = {cc: x * inv % p for cc, x in v.items()}
                piv[c] = v
                r += 1
                break
    return r


def invariant_tensors_linalg(L, k, kind, primes=(1000000007, 998244353)):
    """nullity mod p of the invariance system for symmetric ('S') / alternating ('L') k-tensors."""
    d = L.dim
    wt = L.wt
    zero = tuple(0 for _ in L.cartan)
    add = lambda *ws: tuple(sum(x) for x in zip(*ws))
    if kind == 'S':
        idxs = [t for t in itertools.combinations_with_replacement(range(d), k) if add(*[wt[i] for i in t]) == zero]
    else:
        idxs = [t for t in itertools.combinations(range(d), k) if add(*[wt[i] for i in t]) == zero]
    unk = {t: n for n, t in enumerate(idxs)}

    def canon(t):
        if kind == 'S':
            return tuple(sorted(t)), 1
        if len(set(t)) < len(t):
            return None, 0
        srt = sorted(t)
        perm = [srt.index(x) for x in t]
        sg = 1
        for i in range(len(perm)):
            for j in range(i + 1, len(perm)):
                if perm[i] > perm[j]:
                    sg = -sg
        return tuple(srt), sg
    rows = []
    fu = L.fu
    # targets: index tuples b with weight(b) + weight(y) = 0; equation sum_i T(b_1..[y,b_i]..b_k) = 0
    by_wt = {}
    for a in range(d):
        by_wt.setdefault(wt[a], []).append(a)
    for y in range(d):
        wy = wt[y]
        if kind == 'S':
            tg = [t for t in itertools.combinations_with_replacement(range(d), k)
                  if add(wy, *[wt[i] for i in t]) == zero]
        else:
            tg = [t for t in itertools.combinations(range(d), k) if add(wy, *[wt[i] for i in t]) == zero]
        for t in tg:
            row = {}
            for i in range(k):
                for c in np.nonzero(fu[y, t[i]])[0]:
                    tt = list(t); tt[i] = int(c)
                    key, sg = canon(tuple(tt))
                    if key is None:
                        continue
                    n = unk[key]
                    row[n] = row.get(n, 0) + sg * int(fu[y, t[i], c])
            row = {c: x for c, x in row.items() if x}
            if row:
                rows.append(row)
    nul = [len(idxs) - rank_mod(rows, len(idxs), p) for p in primes]
    return nul, len(idxs), len(rows)
