"""Linear-algebra dimensions of (Lambda^3 g*)^g, (S^3 g*)^g, (g^{*(x)3})^g for the verifier's constructions.
Invariance imposed under two random integer elements a, b; the Lie subalgebra they generate is computed exactly
(span closure under brackets) and must have dim g, so invariance under a, b is invariance under g.
Nullity modulo p1 = 1000003 and p2 = 999983 (sparse elimination, sympy DomainMatrix over GF(p)); nullity mod p is
an upper bound for the Q-dimension; lower bounds from explicit invariants (f, d = tr(X{Y,Z}) for sl_N)."""
import sys, time, itertools
import numpy as np
import sympy as sp
from sympy.polys.matrices import DomainMatrix
from sympy import GF
import valg

P1, P2 = 1000003, 999983


def generated_dim(A, gens):
    basis = []          # echelon basis over Q (Fractions via sympy)
    M = sp.zeros(0, A.n)
    vecs = [np.array(g, dtype=object) for g in gens]
    span = []

    def rank_of(vs):
        return valg.exact_rank([list(map(int, v)) for v in vs]) if vs else 0
    span = list(vecs)
    r = rank_of(span)
    while True:
        new = list(span)
        for x in span:
            for y in span:
                z = A.bracket_vec(x, y)
                if any(z):
                    new.append(z)
        # keep an independent subset
        ind = []
        for v in new:
            if rank_of(ind + [v]) > len(ind):
                ind.append(v)
        if len(ind) == len(span) and rank_of(ind) == r:
            return len(ind)
        span = ind
        r = len(ind)
        if r == A.n:
            return r


def nullity(A, kind, gens, p):
    n = A.n
    if kind == 'S3':
        keys = list(itertools.combinations_with_replacement(range(n), 3))
        canon = lambda t: tuple(sorted(t))
        sign = lambda t: 1
    elif kind == 'L3':
        keys = list(itertools.combinations(range(n), 3))

        def canon(t):
            return tuple(sorted(t)) if len(set(t)) == 3 else None

        def sign(t):
            return 0 if len(set(t)) < 3 else valg_perm_sign(t)
    else:
        keys = list(itertools.product(range(n), repeat=3))
        canon = lambda t: t
        sign = lambda t: 1
    idx = {k: i for i, k in enumerate(keys)}
    rows = {}
    r = 0
    for g in gens:
        adg = np.einsum('a,abm->bm', np.array(g, dtype=np.int64), A.c)     # [g, e_b] = sum_m adg[b,m] e_m
        for t in keys:
            row = {}
            for slot in range(3):
                b = t[slot]
                for m in np.nonzero(adg[b])[0]:
                    tt = list(t)
                    tt[slot] = int(m)
                    tt = tuple(tt)
                    ck = canon(tt)
                    if ck is None:
                        continue
                    sg = sign(tt)
                    row[idx[ck]] = (row.get(idx[ck], 0) + sg * int(adg[b, m])) % p
            row = {k: v for k, v in row.items() if v}
            if row:
                rows[r] = row
                r += 1
    from sympy.polys.matrices.sdm import SDM
    K = GF(p)
    sdm = SDM({i: {j: K(v) for j, v in row.items()} for i, row in rows.items()}, (r, len(keys)), K)
    rank = DomainMatrix.from_rep(sdm).rank()
    return len(keys) - rank


def valg_perm_sign(t):
    s = 1
    t = list(t)
    for i in range(3):
        for j in range(i + 1, 3):
            if t[i] > t[j]:
                s = -s
    return s


rng = np.random.default_rng(17)
for name in sys.argv[1:]:
    t0 = time.time()
    A = valg.build(name)
    gens = [rng.integers(-3, 4, A.n), rng.integers(-3, 4, A.n)]
    gd = generated_dim(A, gens)
    out = ["%-4s dim %d: Lie algebra generated by the two invariance elements: dim %d" % (name, A.n, gd)]
    kinds = ['L3', 'S3'] + (['T3'] if A.n <= 10 else [])
    for k in kinds:
        out.append("   %s: nullity mod p1, p2 = %d, %d" % (k, nullity(A, k, gens, P1), nullity(A, k, gens, P2)))
    out.append("   (%.1fs)" % (time.time() - t0))
    print("\n".join(out), flush=True)
