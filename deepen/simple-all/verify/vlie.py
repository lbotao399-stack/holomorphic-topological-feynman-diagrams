"""Independent Lie algebra constructions for the simple-all verification (no code imported from the explorer).

LA: basis e_0..e_{d-1}, [e_a, e_b] = sum_c C[a,b,c] e_c, stored as integer COO (A, B, Cc, V) with common denominator den
(C = V/den).  Killing form K[a,b] = tr(ad e_a ad e_b) computed exactly (Fractions).

Constructions:
  sl_N        matrices, basis E_ij (i != j), H_i = E_ii - E_{i+1,i+1}
  so_N        matrices, basis E_ij - E_ji (i < j)
  sp_N        N = 2n, J = [[0, I], [-I, 0]], basis {A: E_ij - E_{n+j,n+i}}, {B: E_{i,n+j} + E_{j,n+i}}, {C: E_{n+i,j} + E_{n+j,i}}
  G2          stabilizer in so7 of phi = e123 + e145 + e167 + e246 - e257 - e347 - e356 (exact nullspace)
  F4          so9 + S16 (real Clifford module of Cl(9,0) from Pauli strings), [s,t] = sum_{i<j} (s^T rho(M_ij) t) M_ij
  FK(type)    Frenkel-Kac construction from a simply-laced Cartan matrix (E6, E7, E8, also A_n, D_n):
              [h_i, e_a] = (alpha_i, a) e_a, [e_a, e_b] = eps(a,b) e_{a+b} (a+b root), [e_a, e_-a] = eps(a,-a) h_a,
              eps(a,b) = (-1)^{a^T B b}, B upper triangular: B_ii = 1, B_ij = 1 (i<j adjacent)
Checks (exact, integers): antisymmetry, Jacobi on all index quadruples (sparse), invariance of the Killing form
(f totally antisymmetric), nondegeneracy, rank of a Cartan subalgebra, simplicity (ideal generated by a basis vector
is everything, mod p).
"""
import itertools
import numpy as np
import scipy.sparse as sps
from fractions import Fraction as Fr
import sympy as sp


def perm_sign(seq):
    seq = list(seq); s = 1
    for i in range(len(seq)):
        for j in range(i + 1, len(seq)):
            if seq[i] > seq[j]:
                s = -s
    return s


class LA:
    def __init__(self, name, d, entries, den=1, rank=None, kappaV=None):
        """entries: dict (a,b) -> dict c -> int (only a<b needed; antisymmetrized here)."""
        self.name, self.d, self.den, self.rank = name, d, int(den), rank
        A, B, Cc, V = [], [], [], []
        for (a, b), vec in entries.items():
            for c, v in vec.items():
                if v == 0:
                    continue
                A += [a, b]; B += [b, a]; Cc += [c, c]; V += [v, -v]
        self.A = np.array(A, dtype=np.int64); self.B = np.array(B, dtype=np.int64)
        self.Cc = np.array(Cc, dtype=np.int64); self.V = np.array(V, dtype=np.int64)
        self.kappaV = kappaV          # optional trace form (Fractions matrix) of a defining representation
        self._killing()

    # ad_a[c, b] = C[a, b, c]
    def ad_stack(self):
        d = self.d
        return sps.csr_matrix((self.V, (self.A * d + self.Cc, self.B)), shape=(d * d, d))

    def _killing(self):
        d = self.d
        # K[a,b] = sum_{c,e} C[a,e,c] C[b,c,e]  (integer numerators, / den^2)
        M = sps.csr_matrix((self.V, (self.A, self.B * d + self.Cc)), shape=(d, d * d))   # [a, (e,c)]
        Mt = sps.csr_matrix((self.V, (self.A, self.Cc * d + self.B)), shape=(d, d * d))  # [b, (e,c)] = C[b,c,e]
        assert np.abs(self.V).max() ** 2 * d * d < 2 ** 62
        Kn = (M @ Mt.T).toarray().astype(np.int64)
        self.Knum = Kn
        self.K = [[Fr(int(Kn[a, b]), self.den ** 2) for b in range(d)] for a in range(d)]

    def check_antisym(self):
        return True   # by construction (entries antisymmetrized)

    def check_jacobi(self):
        d = self.d
        # J1[(a,b),(c,g)] = sum_e C[a,b,e] C[e,c,g]
        M1 = sps.csr_matrix((self.V, (self.A * d + self.B, self.Cc)), shape=(d * d, d))
        M2 = sps.csr_matrix((self.V, (self.A, self.B * d + self.Cc)), shape=(d, d * d))
        J = (M1 @ M2).tocoo()
        a, b = J.row // d, J.row % d
        c, g = J.col // d, J.col % d
        vals = J.data.astype(np.int64)
        key = lambda a, b, c, g: ((a * d + b) * d + c) * d + g
        keys = np.concatenate([key(a, b, c, g), key(c, a, b, g), key(b, c, a, g)])  # term(a,b,c) + term(b,c,a) + term(c,a,b)
        vv = np.concatenate([vals, vals, vals])
        o = np.argsort(keys)
        keys, vv = keys[o], vv[o]
        u, st = np.unique(keys, return_index=True)
        s = np.add.reduceat(vv, st) if len(vv) else vv
        return bool(np.all(s == 0)), int(J.nnz)

    def f_dense(self):
        """f[a,b,c] = K([e_a,e_b], e_c) as Fractions (dense, small d only)."""
        d = self.d
        F = np.zeros((d, d, d), dtype=object)
        F[:] = Fr(0)
        for a, b, c, v in zip(self.A, self.B, self.Cc, self.V):
            for e in range(d):
                if self.Knum[c, e] != 0:
                    F[a, b, e] += Fr(int(v) * int(self.Knum[c, e]), self.den ** 3)
        return F

    def check_invariance(self):
        """f(a,b,c) = K([a,b],c) totally antisymmetric (integer numerators)."""
        d = self.d
        M = sps.csr_matrix((self.V, (self.A * d + self.B, self.Cc)), shape=(d * d, d))
        Kn = sps.csr_matrix(self.Knum.astype(np.int64))
        Fm = (M @ Kn).tocoo()
        a, b, c = Fm.row // d, Fm.row % d, Fm.col
        key1 = (a * d + b) * d + c
        key2 = (a * d + c) * d + b
        D = {}
        for k, v in zip(key1, Fm.data):
            D[int(k)] = D.get(int(k), 0) + int(v)
        ok = True
        for k, v in zip(key2, Fm.data):
            # f(a,c,b) should equal -f(a,b,c)
            if D.get(int(k), 0) != -int(v):
                ok = False; break
        return ok

    def mod(self, p):
        """structure constants, Killing, Killing^{-1} mod p."""
        dinv = pow(self.den, p - 2, p)
        V = (self.V % p) * dinv % p
        K = np.array([[(x.numerator % p) * pow(x.denominator, p - 2, p) % p for x in row] for row in self.K], dtype=np.int64)
        Kinv = inv_mod(K, p)
        return V, K, Kinv


def inv_mod(M, p):
    n = M.shape[0]
    A = np.concatenate([M % p, np.eye(n, dtype=np.int64)], axis=1).astype(np.int64)
    for i in range(n):
        piv = None
        for r in range(i, n):
            if A[r, i] % p:
                piv = r; break
        if piv is None:
            raise ValueError("singular mod p")
        A[[i, piv]] = A[[piv, i]]
        A[i] = A[i] * pow(int(A[i, i]), p - 2, p) % p
        col = A[:, i].copy(); col[i] = 0
        nz = np.nonzero(col)[0]
        if len(nz):
            A[nz] = (A[nz] - np.outer(col[nz], A[i]) % p) % p
    return A[:, n:] % p


def rank_mod(M, p):
    A = np.array(M, dtype=np.int64) % p
    r = 0
    rows, cols = A.shape
    for c in range(cols):
        piv = None
        for i in range(r, rows):
            if A[i, c]:
                piv = i; break
        if piv is None:
            continue
        A[[r, piv]] = A[[piv, r]]
        A[r] = A[r] * pow(int(A[r, c]), p - 2, p) % p
        col = A[:, c].copy(); col[r] = 0
        nz = np.nonzero(col)[0]
        if len(nz):
            A[nz] = (A[nz] - np.outer(col[nz], A[r]) % p) % p
        r += 1
        if r == rows:
            break
    return r


def structure_checks(L, p=1000003, seed=1):
    """rank of Cartan (centralizer of a random element), simplicity (ideal generated by basis vector 0), Killing det != 0."""
    d = L.d
    V, K, Kinv = L.mod(p)
    rng = np.random.default_rng(seed)
    x = rng.integers(0, p, d)
    adst = sps.csr_matrix((V, (L.A * d + L.Cc, L.B)), shape=(d * d, d))
    # ad(x)[c,b] = sum_a x_a C[a,b,c]
    adS2 = sps.csr_matrix((V, (L.A, L.Cc * d + L.B)), shape=(d, d * d))
    adx = (sps.csr_matrix(x.reshape(1, d)) @ adS2).toarray().reshape(d, d) % p
    rk = d - rank_mod(adx, p)
    # ideal generated by e_0: closure under ad(e_a) for all a
    ads = [(adst[a * d:(a + 1) * d, :]).toarray() % p for a in range(d)]
    R = np.zeros((0, d), dtype=np.int64); pivs = []
    frontier = [np.eye(d, dtype=np.int64)[0]]
    while frontier and len(pivs) < d:
        v = frontier.pop() % p
        if pivs:
            v = (v - (v[pivs] @ R) % p) % p
        nz = np.nonzero(v)[0]
        if len(nz) == 0:
            continue
        c = nz[0]
        v = v * pow(int(v[c]), p - 2, p) % p
        if len(pivs):
            R = (R - np.outer(R[:, c], v) % p) % p
        R = np.vstack([R, v.reshape(1, d)]); pivs.append(c)
        for a in range(d):
            w = ads[a] @ v % p
            if w.any():
                frontier.append(w)
    return rk, len(pivs), True


# ---------------------------------------------------------------------------------------------- matrix algebras
def from_matrices(name, mats, coords, rank=None):
    """mats: list of integer (or Fraction) numpy object matrices; coords(M) -> dict index -> Fraction."""
    d = len(mats)
    ent = {}
    dens = 1
    raw = {}
    for a in range(d):
        for b in range(a + 1, d):
            M = mats[a].dot(mats[b]) - mats[b].dot(mats[a])
            cd = coords(M)
            # reconstruction check
            R = sum((v * mats[c] for c, v in cd.items()), np.zeros_like(M))
            assert np.all(R == M), (name, a, b)
            raw[(a, b)] = cd
            for v in cd.values():
                dens = dens * Fr(v).denominator // __import__('math').gcd(dens, Fr(v).denominator)
    for k, cd in raw.items():
        ent[k] = {c: int(Fr(v) * dens) for c, v in cd.items()}
    kV = [[Fr(np.trace(mats[a].dot(mats[b]))) for b in range(d)] for a in range(d)]
    return LA(name, d, ent, den=dens, rank=rank, kappaV=kV)


def Emat(N, i, j):
    M = np.zeros((N, N), dtype=object); M[:] = 0
    M[i, j] = 1
    return M


def sl(N):
    mats, idx = [], {}
    for i in range(N):
        for j in range(N):
            if i != j:
                idx[('E', i, j)] = len(mats); mats.append(Emat(N, i, j))
    for i in range(N - 1):
        idx[('H', i)] = len(mats); mats.append(Emat(N, i, i) - Emat(N, i + 1, i + 1))

    def coords(M):
        out = {}
        for i in range(N):
            for j in range(N):
                if i != j and M[i, j] != 0:
                    out[idx[('E', i, j)]] = Fr(M[i, j])
        s = Fr(0)
        for i in range(N - 1):
            s += Fr(M[i, i])
            if s != 0:
                out[idx[('H', i)]] = s
        return out
    return from_matrices('sl%d(mat)' % N, mats, coords, rank=N - 1)


def so(N):
    mats, idx = [], {}
    for i in range(N):
        for j in range(i + 1, N):
            idx[(i, j)] = len(mats); mats.append(Emat(N, i, j) - Emat(N, j, i))

    def coords(M):
        return {idx[(i, j)]: Fr(M[i, j]) for i in range(N) for j in range(i + 1, N) if M[i, j] != 0}
    return from_matrices('so%d(mat)' % N, mats, coords, rank=N // 2)


def spn(N):
    n = N // 2
    mats, idx = [], {}
    for i in range(n):
        for j in range(n):
            idx[('A', i, j)] = len(mats); mats.append(Emat(N, i, j) - Emat(N, n + j, n + i))
    for i in range(n):
        for j in range(i, n):
            M = Emat(N, i, n + j) + Emat(N, j, n + i) if i != j else Emat(N, i, n + i)
            idx[('B', i, j)] = len(mats); mats.append(M)
            M = Emat(N, n + i, j) + Emat(N, n + j, i) if i != j else Emat(N, n + i, i)
            idx[('C', i, j)] = len(mats); mats.append(M)
    J = np.zeros((N, N), dtype=object); J[:] = 0
    for i in range(n):
        J[i, n + i] = 1; J[n + i, i] = -1
    for M in mats:
        assert np.all(M.T.dot(J) + J.dot(M) == 0)

    def coords(M):
        out = {}
        for i in range(n):
            for j in range(n):
                if M[i, j] != 0:
                    out[idx[('A', i, j)]] = Fr(M[i, j])
        for i in range(n):
            for j in range(i, n):
                if M[i, n + j] != 0:
                    out[idx[('B', i, j)]] = Fr(M[i, n + j])
                if M[n + i, j] != 0:
                    out[idx[('C', i, j)]] = Fr(M[n + i, j])
        return out
    return from_matrices('sp%d(mat)' % N, mats, coords, rank=n)


def g2():
    """stabilizer of phi in so7 (exact nullspace)."""
    N = 7
    trip = [(1, 2, 3, 1), (1, 4, 5, 1), (1, 6, 7, 1), (2, 4, 6, 1), (2, 5, 7, -1), (3, 4, 7, -1), (3, 5, 6, -1)]
    phi = np.zeros((N, N, N), dtype=object); phi[:] = 0
    for (a, b, c, s) in trip:
        a, b, c = a - 1, b - 1, c - 1
        for perm in itertools.permutations(range(3)):
            idxs = [(a, b, c)[k] for k in perm]
            sg = perm_sign(perm)
            phi[idxs[0], idxs[1], idxs[2]] = s * sg
    so7 = [(i, j) for i in range(N) for j in range(i + 1, N)]
    rows = []
    for (i, j) in so7:
        X = Emat(N, i, j) - Emat(N, j, i)
        # (X.phi)_{abc} = sum_d X_{da} phi_{dbc} + X_{db} phi_{adc} + X_{dc} phi_{abd}
        Y = np.einsum('da,dbc->abc', X, phi) + np.einsum('db,adc->abc', X, phi) + np.einsum('dc,abd->abc', X, phi)
        rows.append([Y[a, b, c] for a in range(N) for b in range(a + 1, N) for c in range(b + 1, N)])
    Mx = sp.Matrix(rows).T     # columns = so7 basis
    ns = Mx.nullspace()
    mats = []
    for v in ns:
        v = v * sp.ilcm(*[sp.Rational(x).q for x in v])
        M = np.zeros((N, N), dtype=object); M[:] = 0
        for k, (i, j) in enumerate(so7):
            M[i, j] += int(v[k]); M[j, i] -= int(v[k])
        mats.append(M)
    # coordinates: pivot solve
    vecs = sp.Matrix([[m[i, j] for (i, j) in so7] for m in mats])   # d x 21
    piv = vecs.rref()[1]
    Pm = vecs[:, list(piv)]            # d x d
    Pinv = Pm.inv()

    def coords(M):
        w = sp.Matrix([[M[i, j] for (i, j) in so7]])[:, list(piv)]
        c = w * Pinv
        return {k: Fr(int(sp.Rational(c[k]).p), int(sp.Rational(c[k]).q)) for k in range(len(mats)) if c[k] != 0}
    return from_matrices('G2(phi in so7)', mats, coords, rank=2)


def pauli_gammas(n_gen, n_fac):
    sx = np.array([[0, 1], [1, 0]]); sz = np.array([[1, 0], [0, -1]]); ep = np.array([[0, 1], [-1, 0]]); I2 = np.eye(2, dtype=int)
    letters = {'I': I2, 'X': sx, 'Z': sz, 'E': ep}
    anti = {('X', 'Z'), ('Z', 'X'), ('X', 'E'), ('E', 'X'), ('Z', 'E'), ('E', 'Z')}
    strings = [''.join(s) for s in itertools.product('IXZE', repeat=n_fac) if s.count('E') % 2 == 0 and set(s) != {'I'}]

    def ac(s, t):
        return sum((a, b) in anti for a, b in zip(s, t)) % 2 == 1
    best = []

    def bt(chosen, start):
        nonlocal best
        if len(chosen) > len(best):
            best = list(chosen)
        if len(best) >= n_gen:
            return True
        for k in range(start, len(strings)):
            s = strings[k]
            if all(ac(s, t) for t in chosen):
                chosen.append(s)
                if bt(chosen, k + 1):
                    return True
                chosen.pop()
        return False
    bt([], 0)
    assert len(best) >= n_gen
    G = []
    for s in best[:n_gen]:
        M = np.array([[1]])
        for ch in s:
            M = np.kron(M, letters[ch])
        G.append(M.astype(np.int64))
    n = 2 ** n_fac
    for i in range(n_gen):
        assert np.all(G[i] == G[i].T) and np.all(G[i] @ G[i] == np.eye(n))
        for j in range(i + 1, n_gen):
            assert np.all(G[i] @ G[j] + G[j] @ G[i] == 0)
    return G, best[:n_gen]


def f4():
    G, strs = pauli_gammas(9, 4)
    N, S = 9, 16
    so9 = [(i, j) for i in range(N) for j in range(i + 1, N)]
    Mv = {}
    for (i, j) in so9:
        X = np.zeros((N, N), dtype=np.int64); X[i, j] = 1; X[j, i] = -1
        Mv[(i, j)] = X
    # spinor rep: try rho(M_ij) = sgn * (1/2) G_i G_j, pick the sign giving a homomorphism
    def rho(i, j, sg):
        return sg * Fr(1, 2) * (G[i] @ G[j]).astype(object)
    chosen = None
    for sg in (1, -1):
        ok = True
        for (i, j) in so9:
            for (k, l) in so9:
                Cm = Mv[(i, j)] @ Mv[(k, l)] - Mv[(k, l)] @ Mv[(i, j)]
                R = sum((Fr(int(Cm[a, b])) * rho(a, b, sg) for (a, b) in so9 if Cm[a, b] != 0), np.zeros((S, S), dtype=object) * Fr(0))
                L = rho(i, j, sg).dot(rho(k, l, sg)) - rho(k, l, sg).dot(rho(i, j, sg))
                if not np.all(L == R):
                    ok = False; break
            if not ok:
                break
        if ok:
            chosen = sg; break
    assert chosen is not None
    rh = {ij: rho(ij[0], ij[1], chosen) for ij in so9}
    d = 36 + 16
    ent = {}
    for a, (i, j) in enumerate(so9):
        for b in range(a + 1, 36):
            k, l = so9[b]
            Cm = Mv[(i, j)] @ Mv[(k, l)] - Mv[(k, l)] @ Mv[(i, j)]
            ent[(a, b)] = {so9.index((x, y)): Fr(int(Cm[x, y])) for (x, y) in so9 if Cm[x, y] != 0}
        for s in range(S):
            col = rh[(i, j)][:, s]
            ent[(a, 36 + s)] = {36 + t: col[t] for t in range(S) if col[t] != 0}
    for s in range(S):
        for t in range(s + 1, S):
            vec = {}
            for c, (i, j) in enumerate(so9):
                val = rh[(i, j)][s, t]          # s^T rho t with s, t basis vectors
                if val != 0:
                    vec[c] = val
            ent[(36 + s, 36 + t)] = vec
    den = 1
    for vec in ent.values():
        for v in vec.values():
            den = den * Fr(v).denominator // __import__('math').gcd(den, Fr(v).denominator)
    ent2 = {k: {c: int(Fr(v) * den) for c, v in vec.items()} for k, vec in ent.items()}
    L = LA('F4(so9+S16)', d, ent2, den=den, rank=4)
    L.gamma_strings = strs; L.rho_sign = chosen
    return L


