def gram(typ, n):
    """symmetric Gram matrix B = (alpha_i, alpha_j), long roots of length^2 2 (G2: long 6, short 2)."""
    B = np.zeros((n, n), dtype=object); B[:] = 0
    if typ == 'A':
        for i in range(n):
            B[i, i] = 2
            if i + 1 < n:
                B[i, i + 1] = B[i + 1, i] = -1
    elif typ == 'B':
        for i in range(n):
            B[i, i] = 2
            if i + 1 < n:
                B[i, i + 1] = B[i + 1, i] = -1
        B[n - 1, n - 1] = 1
    elif typ == 'C':
        for i in range(n):
            B[i, i] = 2
            if i + 1 < n:
                B[i, i + 1] = B[i + 1, i] = -1
        B[n - 1, n - 1] = 4; B[n - 2, n - 1] = B[n - 1, n - 2] = -2
    elif typ == 'D':
        for i in range(n):
            B[i, i] = 2
        for i in range(n - 2):
            B[i, i + 1] = B[i + 1, i] = -1
        B[n - 3, n - 1] = B[n - 1, n - 3] = -1
    elif typ == 'E':
        # Bourbaki: 1-3-4-5-6-7-8, 2-4
        for i in range(n):
            B[i, i] = 2
        edges = [(1, 3), (3, 4), (4, 5), (5, 6), (6, 7), (7, 8), (2, 4)]
        for (a, b) in edges:
            if a <= n and b <= n:
                B[a - 1, b - 1] = B[b - 1, a - 1] = -1
    elif typ == 'F':
        B = np.array([[2, -1, 0, 0], [-1, 2, -1, 0], [0, -1, 1, Fr(-1, 2)], [0, 0, Fr(-1, 2), 1]], dtype=object)
    elif typ == 'G':
        B = np.array([[2, -3], [-3, 6]], dtype=object)
    return B


def positive_roots(B):
    """positive roots in simple-root coordinates (tuples), via alpha_i-strings."""
    n = B.shape[0]
    A = [[Fr(2) * B[i, j] / B[i, i] for j in range(n)] for i in range(n)]    # A_ij = <alpha_j, alpha_i^vee>
    simple = [tuple(1 if k == i else 0 for k in range(n)) for i in range(n)]
    roots = set(simple)
    layer = list(simple)
    while layer:
        new = []
        for r in layer:
            for i in range(n):
                # <r, alpha_i^vee>
                pr = sum(Fr(r[j]) * A[i][j] for j in range(n))
                # p = max k with r - k alpha_i a root (or zero)
                p = 0
                while True:
                    s = list(r); s[i] -= p + 1
                    if tuple(s) in roots:
                        p += 1
                    else:
                        break
                q = p - pr
                if q > 0:
                    s = list(r); s[i] += 1
                    s = tuple(s)
                    if s not in roots:
                        roots.add(s); new.append(s)
        layer = new
    return sorted(roots, key=lambda r: (sum(r), r))


def frenkel_kac(typ, n):
    B = gram(typ, n)
    assert all(B[i, i] == 2 for i in range(n))
    pos = positive_roots(B)
    roots = pos + [tuple(-x for x in r) for r in pos]
    rset = {r: k for k, r in enumerate(roots)}
    Bt = np.zeros((n, n), dtype=np.int64)
    for i in range(n):
        Bt[i, i] = 1
        for j in range(i + 1, n):
            if B[i, j] != 0:
                Bt[i, j] = 1

    def eps(a, b):
        return -1 if (np.array(a) @ Bt @ np.array(b)) % 2 else 1

    def ip(a, b):
        return int(sum(a[i] * B[i, j] * b[j] for i in range(n) for j in range(n)))
    d = n + len(roots)
    E = lambda r: n + rset[r]
    ent = {}

    def add(a, b, vec):
        if a < b:
            ent[(a, b)] = vec
        else:
            ent[(b, a)] = {c: -v for c, v in vec.items()}
    for i in range(n):
        ai = tuple(1 if k == i else 0 for k in range(n))
        for r in roots:
            add(i, E(r), {E(r): ip(ai, r)})
    for x in range(len(roots)):
        for y in range(x + 1, len(roots)):
            a, b = roots[x], roots[y]
            s = tuple(u + v for u, v in zip(a, b))
            if all(v == 0 for v in s):
                vec = {i: eps(a, b) * a[i] for i in range(n) if a[i] != 0}
                add(E(a), E(b), vec)
            elif s in rset:
                add(E(a), E(b), {E(s): eps(a, b)})
    L = LA('%s%d(FK)' % (typ, n), d, ent, den=1, rank=n)
    L.roots = roots
    L.root_norms = sorted(set(ip(r, r) for r in roots))
    return L


def build(key):
    if key.startswith('sl'):
        return sl(int(key[2:]))
    if key.startswith('so'):
        return so(int(key[2:]))
    if key.startswith('sp'):
        return spn(int(key[2:]))
    if key == 'G2':
        return g2()
    if key == 'F4':
        return f4()
    if key in ('E6', 'E7', 'E8'):
        return frenkel_kac('E', int(key[1]))
    if key.startswith('FK'):
        return frenkel_kac(key[2], int(key[3:]))
    raise KeyError(key)


