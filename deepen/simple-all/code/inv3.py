"""dim (Lambda^3 g*)^g, dim (S^3 g*)^g, dim (g^{*(x)3})^g by linear algebra (weight bases).

Unknowns: T on h-weight-zero index triples (sorted: subsets for Lambda^3, multisets for S^3, ordered triples for T^3).
Equations: (y.T)(a,b,c) = -T([y,a],b,c) - T(a,[y,b],c) - T(a,b,[y,c]) = 0 for y in a generating set
(simple root vectors E_{+-alpha_i}; the generated subalgebra is checked to be all of g) and all (a,b,c) of
weight -wt(y).  A weight-zero T annihilated by a generating set is g-invariant (and conversely).
rank modulo p (two primes): nullity mod p >= nullity over Q, so nullity mod p is an upper bound; an explicit
invariant (f for Lambda^3) gives the lower bound.
"""
import itertools, sys, time
import numpy as np
import scipy.sparse as sps


def generators(L):
    """simple root vectors E_{+-alpha_i}: weight vectors of weight +- simple roots."""
    d, wt = L.dim, [tuple(int(x) for x in w) for w in L.wt]
    roots = sorted({w for w in wt if any(w)})
    gen = [1000003 ** i for i in range(len(L.cartan))][::-1]
    val = lambda w: sum(x * g for x, g in zip(w, gen))
    pos = [w for w in roots if val(w) > 0]
    possum = {tuple(a + b for a, b in zip(x, y)) for x in pos for y in pos}
    simple = [w for w in pos if w not in possum]
    assert len(simple) == len(L.cartan)
    G = []
    for w in simple:
        for sgn in (1, -1):
            ww = tuple(sgn * x for x in w)
            G += [a for a in range(d) if wt[a] == ww]
    return G


def generated_dim(L, gens):
    """dimension of the Lie subalgebra generated by gens (exact rank over Q via sympy on the span)."""
    import sympy as sp
    d = L.dim
    basis = []          # list of dict vectors in echelon form (Fraction)
    from fractions import Fraction as Fr
    piv = {}

    def add(v):
        v = {k: Fr(x) for k, x in v.items() if x}
        for c in sorted(piv):
            if c in v:
                f = v[c]
                for k, x in piv[c].items():
                    v[k] = v.get(k, 0) - f * x
                v = {k: x for k, x in v.items() if x}
        if not v:
            return False
        c = min(v)
        f = v[c]
        piv[c] = {k: x / f for k, x in v.items()}
        # keep echelon: reduce others not needed for rank
        return True
    vecs = []
    for g in gens:
        e = {g: 1}
        if add(e):
            vecs.append(e)
    frontier = list(vecs)
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                # [e_g, x]
                y = {}
                m = L.A == g
                for b, c, v in zip(L.B[m], L.C[m], L.V[m]):
                    if b in x:
                        y[c] = y.get(c, 0) + int(v) * x[b]
                y = {k: v for k, v in y.items() if v}
                if y and add(y):
                    new.append(y)
        frontier = new
    return len(piv)


def bracket_table(L):
    """tab[y][b] = list of (c, v) with [e_y, e_b] = sum v e_c."""
    tab = {}
    for a, b, c, v in zip(L.A, L.B, L.C, L.V):
        tab.setdefault(int(a), {}).setdefault(int(b), []).append((int(c), int(v)))
    return tab


def rank_mod(rows, p):
    piv = {}
    r = 0
    for row in rows:
        v = {c: x % p for c, x in row.items() if x % p}
        while v:
            c = min(v)
            if c in piv:
                pr = piv[c]
                f = v[c]
                for cc, x in pr.items():
                    nv = (v.get(cc, 0) - f * x) % p
                    if nv:
                        v[cc] = nv
                    else:
                        v.pop(cc, None)
            else:
                inv = pow(v[c], p - 2, p)
                piv[c] = {cc: x * inv % p for cc, x in v.items()}
                r += 1
                break
    return r


def invariant_dim(L, kind, primes=(1000003, 999983), gens=None):
    d = L.dim
    wt = [tuple(int(x) for x in w) for w in L.wt]
    by_w = {}
    for a in range(d):
        by_w.setdefault(wt[a], []).append(a)
    zero = tuple(0 for _ in L.cartan)
    add = lambda *ws: tuple(sum(x) for x in zip(*ws))

    def triples(target):
        """index triples (sorted per kind) with weight sum = target."""
        out = []
        ws = list(by_w)
        for w1 in ws:
            for w2 in ws:
                w3 = tuple(t - x - y for t, x, y in zip(target, w1, w2))
                if w3 not in by_w:
                    continue
                for a in by_w[w1]:
                    for b in by_w[w2]:
                        for c in by_w[w3]:
                            t = (a, b, c)
                            if kind == 'T':
                                out.append(t)
                            elif kind == 'S':
                                if a <= b <= c:
                                    out.append(t)
                            else:
                                if a < b < c:
                                    out.append(t)
        return out
    unk = {t: n for n, t in enumerate(triples(zero))}

    def canon(t):
        if kind == 'T':
            return t, 1
        s = tuple(sorted(t))
        if kind == 'S':
            return s, 1
        if len(set(t)) < 3:
            return None, 0
        perm = [s.index(x) for x in t]
        sg = 1
        for i in range(3):
            for j in range(i + 1, 3):
                if perm[i] > perm[j]:
                    sg = -sg
        return s, sg
    tab = bracket_table(L)
    if gens is None:
        gens = generators(L)
    rows = []
    for y in gens:
        ty = tab.get(y, {})
        target = tuple(-x for x in wt[y])
        for t in triples(target):
            row = {}
            for i in range(3):
                for c, v in ty.get(t[i], []):
                    tt = list(t); tt[i] = c
                    key, sg = canon(tuple(tt))
                    if key is None:
                        continue
                    n = unk[key]
                    row[n] = row.get(n, 0) + sg * v
            row = {c: x for c, x in row.items() if x}
            if row:
                rows.append(row)
    nul = [len(unk) - rank_mod(rows, p) for p in primes]
    return nul, len(unk), len(rows), len(gens)


