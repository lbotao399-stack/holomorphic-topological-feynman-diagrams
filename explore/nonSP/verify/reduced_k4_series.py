"""Exact K4 period from the five-variable reduced density P/Q^10.

Input only: the retained P.m polynomial. No Mathematica integrals, one-dimensional
exports, numerical periods, or PSLQ are used. With gC=1-gA-gB, homogenize P to
degree D in g. Expand (1-sum_i g_i r_i)^(-10), integrate the original simplices
termwise for a radial cutoff below one, then use
 (N+9)!/(N+D+2)! = integral x^(N+9)(1-x)^(D-8) dx/(D-8)!.
Each factor S(a,b)=sum_(n>=0) (n+a)!/n! * x^n/(n+b+1) is generated by
S(a,b)=(x*d/dx+a)S(a-1,b). S(0,b)=x^(-b-1)*[-log(1-x)-sum_(j=1)^b x^j/j].
"""
from collections import defaultdict
from fractions import Fraction as F
from functools import cache
from itertools import product
from math import comb, factorial, lcm, prod
from pathlib import Path
import re
import sys

import sympy as sp

BASE = Path(__file__).resolve().parents[1]
VARIABLES = ('gA','gB','rA','rB','rC')


def read_homogeneous(path):
    raw = {}
    source = ''.join(path.read_text().split()).replace('(','').replace(')','')
    for sign,monomial in re.findall(r'([+-]?)([^+-]+)',source):
        a=[0]*5
        coefficient=F(-1 if sign=='-' else 1)
        for factor in monomial.replace('/','*/').split('*'):
            if factor.startswith('/'):
                coefficient/=int(factor[1:])
            elif factor.isdigit():
                coefficient*=int(factor)
            else:
                var,_,power=factor.partition('^')
                a[VARIABLES.index(var)]+=int(power or 1)
        a=tuple(a);raw[a]=raw.get(a,0)+coefficient
    D=max(k[0]+k[1] for k in raw)
    ans=defaultdict(F)
    for (g,h,*r),coef in raw.items():
        n=D-g-h
        for i in range(n+1):
            for j in range(n-i+1):
                ans[(g+i,h+j,n-i-j,*r)]+=coef*comb(n,i)*comb(n-i,j)
    return D,{k:v for k,v in ans.items() if v}


def convergence(terms,D,power=10):
    # Expand r_i=1-rho_i first, preserving cancellations at the singular corner.
    # After Feynman combination, each nonnegative g^a rho^b term is integrable
    # separately if D-7 > sum_i max(a_i-b_i,0); equality of an exponent adds
    # at most one logarithm. The finite test proves absolute domination.
    at_corner=defaultdict(F)
    for k,val in terms.items():
        for q in product(*(range(b+1) for b in k[3:])):
            at_corner[k[:3]+q]+=val*(-1)**sum(q)*prod(comb(b,i) for b,i in zip(k[3:],q))
    margins = [D+3-power-sum(max(a-b,0) for a,b in zip(k[:3],k[3:])) for k,v in at_corner.items() if v]
    assert min(margins)>0, ('power-counting corner condition',min(margins))
    return min(margins)


def times_x_derivative(polynomial,a,M,log_part):
    # New numerator for x^M(1-x)^a S(a,b). Account for d log(1-x)/dx separately.
    ans=[0]*(len(polynomial)+1)
    for k,v in enumerate(polynomial):
        ans[k]+=(k+a-M)*v
        ans[k+1]+=(M-1-k)*v
    for k,v in enumerate(log_part):
        ans[k+1]-=v
    return ans


def evaluate(poly,x):
    value=0
    for c in reversed(poly):
        value=value*x+c
    return value


def one_dimension(D,terms,power=10):
    M=1+max(max(k[3:]) for k in terms)
    denominator=lcm(*(c.denominator for c in terms.values()))
    ss=lcm(*range(1,M+1))
    @cache
    def factors(a,b):
        if a:
            R,L=factors(a-1,b)
            return times_x_derivative(R,a,M,L),times_x_derivative(L,a,M,[])
        R=[0]*M
        L=[0]*M
        L[M-b-1]=-ss
        for j in range(1,b+1):
            R[M-b-1+j]=-ss//j
        return R,L
    inputs=[(tuple(zip(k[:3],k[3:])),int(c*denominator)) for k,c in terms.items()]
    pairs_used={pair for pairs,_ in inputs for pair in pairs}
    maxdegree=3*(M-1)+D
    values=[[] for _ in range(4)]
    for x in range(maxdegree+1):
        basis={pair:tuple(evaluate(p,x) for p in factors(*pair)) for pair in pairs_used}
        v=[0]*4
        for (p,q,r),coef in inputs:
            A,a=basis[p];B,b=basis[q];C,c=basis[r]
            v[0]+=coef*A*B*C
            v[1]+=coef*(a*B*C+A*b*C+A*B*c)
            v[2]+=coef*(a*b*C+a*B*c+A*b*c)
            v[3]+=coef*a*b*c
        for row,num in zip(values,v):row.append(num)
    X=sp.Symbol('x')
    ring=sp.Poly(1,X,domain=sp.QQ)
    norm=denominator*ss**3*factorial(power-1)*factorial(D+2-power)
    polys=[]
    for ys in values:
        poly,fall=ring.zero,ring.one
        for n in range(maxdegree+1):
            poly+=fall*ys[0]
            fall=fall*sp.Poly(X-n,X,domain=sp.QQ)/sp.Integer(n+1)
            fall=sp.Poly(fall,X,domain=sp.QQ)
            ys=[b-a for a,b in zip(ys,ys[1:])]
        quotient,remainder=divmod(poly,sp.Poly((1-X)**(power-2),X,domain=sp.QQ))
        assert remainder.is_zero, 'uncancelled pole at x=1'
        polys.append({ex[0]+power-1-3*M:F(coef)/norm for ex,coef in quotient.terms() if coef})
    return polys


def beta_finite_parts(polys):
    # The envelope is sum h[k,e] x^e log(1-x)^k. Insert x^z and use the
    # constant Laurent term of (d/db)^k B(1+e+z,1+b). For e=-1,-2,...,
    # Gamma(1+z)Gamma(1+b)/Gamma(1+z+b)
    # = 1+z sum_(r>=1)(-1)^r zeta(r+1) b^r+O(z^2).
    coeff=defaultdict(F)
    residue=F(0)
    b=sp.Symbol('b')
    for k,row in enumerate(polys):
        for e,h in row.items():
            if e>=0:
                coeff[0]+=h*(-1)**k*factorial(k)*sum(F((-1)**j*comb(e,j),(j+1)**(k+1))
                                                     for j in range(e+1))
                continue
            m=e+1
            num=sp.Poly(prod(b+j for j in range(m+1,1)),b)
            den=prod(range(m,0))
            harm=sum((F(1,j) for j in range(m,0)),F(0))
            scale=h*factorial(k)/den
            residue+=scale*int(num.nth(k))
            coeff[0]+=scale*(int(num.diff().nth(k))-harm*int(num.nth(k)))
            for r in range(1,k+1):
                coeff[r+1]+=scale*(-1)**r*int(num.nth(k-r))
    assert not residue
    return {k:v for k,v in coeff.items() if v}


if __name__=='__main__':
    for case in sys.argv[1:] or ['case0_D0']:
        D,terms=read_homogeneous(BASE/'out'/f'{case}_P.m')
        margin=convergence(terms,D)
        rows=one_dimension(D,terms)
        result=beta_finite_parts(rows)
        print(case,'D',D,'homogeneous terms',len(terms),'absolute margin',margin,
              'coefficients 1,zeta(k):',result,flush=True)
