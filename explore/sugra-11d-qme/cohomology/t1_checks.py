def subst_exact(n, maxord, sX=-1):
    """phi: mu^i_a := D^a((1-nu) X^i).  Check Q_strict(mu^i_a) == D^a(-D_j((1-nu) X^j X^i)) exactly,
    and the formulas Q nu, Q gamma, Q beta against R-Q0 with f mu = X, f^2 mu mu = X X."""
    A = Alg(n, quot=False, sX=sX)
    z = (0,) * n
    one = {(): 1}
    rho = A.padd(one, A.letter('n', 0, z), -1)  # 1 - nu
    ok = True
    nchk = 0
    for m in range(maxord + 1):
        for a in multi_indices(n, m):
            for i in range(n):
                mu = A.pmul(rho, A.letter('X', i, z))
                for k in range(n):
                    for _ in range(a[k]):
                        mu = A.D(mu, k)
                lhs = A.Q(mu)
                rhs = {}
                for j in range(n):
                    t = A.prod(rho, A.letter('X', j, z), A.letter('X', i, z))
                    rhs = A.padd(rhs, A.D(t, j), -1)
                for k in range(n):
                    for _ in range(a[k]):
                        rhs = A.D(rhs, k)
                nchk += 1
                if A.padd(lhs, rhs, -1):
                    ok = False
    return ok, nchk


def subst_series(n, maxord, numax=2, K=4):
    """Source variables (mu, nu, gamma, beta) with Q_source of R-Q0 (g=0), f = sum_{k<=K} nu^k.
    psi(X^i_a) = D^a(f mu^i), psi = id on nu, gamma, beta.  Check Q_source psi(phi_a) == psi(Q_strict phi_a)
    modulo nu-degree > numax, for all generators with |a| <= maxord.  Letters 'X' of the algebra below
    stand for mu."""
    S = Alg(n, quot=False, sX=-1)   # carrier of mu-variables (letter type 'X' = mu)
    z = (0,) * n
    e = [unit(n, k) for k in range(n)]
    nu = S.letter('n', 0, z)

    def trunc(p, d=K):
        return {m: c for m, c in p.items() if sum(1 for x in m if S.info[x][0] == 'n') <= d}

    def fpow(p):
        r = {}
        term = {(): 1}
        for k in range(K + 1):
            r = S.padd(r, term)
            term = trunc(S.pmul(term, nu))
        return r

    f = fpow(1)
    f2 = trunc(S.pmul(f, f))
    mu = [S.letter('X', i, z) for i in range(n)]
    ga = [S.letter('g', i, z) for i in range(n)]
    be = S.letter('b', 0, z)

    def Dp(p, a):
        for k in range(n):
            for _ in range(a[k]):
                p = trunc(S.D(p, k))
        return p

    # source Q on base letters
    Qs = {}
    Qs[('n', 0)] = {}
    for i in range(n):
        Qs[('n', 0)] = S.padd(Qs[('n', 0)], S.letter('X', i, e[i]))
    for i in range(n):
        r = {}
        for j in range(n):
            r = S.padd(r, Dp(trunc(S.prod(f, mu[j], mu[i])), e[j]), -1)
        Qs[('X', i)] = r
    r = {}
    for i in range(n):
        for j in range(n):
            r = S.padd(r, trunc(S.prod(f2, mu[i], mu[j], S.letter('g', j, e[i]))))
    Qs[('b', 0)] = r
    for i in range(n):
        r = S.letter('b', 0, e[i])
        for k in range(n):
            F = S.padd(S.letter('g', k, e[i]), S.letter('g', i, e[k]), -1)
            r = S.padd(r, trunc(S.prod(f, mu[k], F)))
        Qs[('g', i)] = r
    memo = {}

    def Qsl(lid):
        if lid in memo:
            return memo[lid]
        typ, i, a = S.info[lid]
        if sum(a) == 0:
            r = Qs[(typ, i)]
        else:
            k = next(j for j in range(n) if a[j] > 0)
            b = list(a)
            b[k] -= 1
            r = trunc(S.D(Qsl(S.L(typ, i, tuple(b))), k))
        memo[lid] = r
        return r

    def Qsrc(p):
        return trunc(S.apply_der(p, Qsl, True))

    # psi on strict letters
    St = Alg(n, quot=False, sX=-1)

    def psi_letter(lid):
        typ, i, a = St.info[lid]
        if typ == 'X':
            return Dp(trunc(S.pmul(f, mu[i])), a)
        return S.letter(typ, i, a)

    def psi(p):
        r = {}
        for m, c in p.items():
            acc = {(): c}
            for x in m:
                acc = trunc(S.pmul(acc, psi_letter(x)))
            r = S.padd(r, acc)
        return r

    def low(p):
        return {m: c for m, c in p.items() if sum(1 for x in m if S.info[x][0] == 'n') <= numax}

    ok = True
    nchk = 0
    for m in range(maxord + 1):
        for a in multi_indices(n, m):
            for typ in TYPES:
                for i in (range(n) if typ in ('X', 'g') else [0]):
                    lid = St.L(typ, i, a)
                    lhs = low(Qsrc(psi({(lid,): 1})))
                    rhs = low(psi(St.Qletter(lid)))
                    nchk += 1
                    if S.padd(lhs, rhs, -1):
                        ok = False
                        log('   mismatch', St.name(lid))
    return ok, nchk


