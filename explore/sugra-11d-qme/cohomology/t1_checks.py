"""T1: Q^2 = 0 on generators; substitution mu = (1-nu) X against R-Q0 (g = 0); gradings.
Writes t1.log."""
import sys, time
from jets import Alg, multi_indices, unit, TYPES

out = open('t1.log', 'w')


def log(*a):
    s = ' '.join(str(x) for x in a)
    print(s)
    out.write(s + '\n')
    out.flush()


def gens(n, maxord):
    for m in range(maxord + 1):
        for a in multi_indices(n, m):
            for typ in TYPES:
                for i in (range(n) if typ in ('X', 'g') else [0]):
                    yield typ, i, a


def check_Q2(n, maxord, sX):
    A = Alg(n, quot=False, sX=sX)
    bad = []
    cnt = 0
    for typ, i, a in gens(n, maxord):
        lid = A.L(typ, i, a)
        q2 = A.Q(A.Qletter(lid))
        cnt += 1
        if q2:
            bad.append((A.name(lid), A.pstr(q2, 6)))
    return cnt, bad


def check_gradings(n, maxord, sX=-1):
    """Q preserves w, G, t; raises N = #X + #beta by 1; arity raised by >= 0, arity-preserving part only from
    d_i X^i in Q nu and d_i beta in Q gamma."""
    A = Alg(n, quot=False, sX=sX)
    ok = True
    lin = {}
    for typ, i, a in gens(n, maxord):
        lid = A.L(typ, i, a)
        G0, t0 = A.weight((lid,))
        w0 = A.wdeg((lid,))
        N0 = A.Ndeg((lid,))
        for m, c in A.Qletter(lid).items():
            G, t = A.weight(m)
            if G != G0 or t != t0 or A.wdeg(m) != w0 or A.Ndeg(m) != N0 + 1 or len(m) < 1:
                ok = False
            if len(m) == 1:
                lin.setdefault(typ, set()).add(A.info[m[0]][0])
    return ok, {k: sorted(v) for k, v in lin.items()}


def check_div_ideal(n, maxord):
    """Q(div_a) lies in the ideal generated by the div_b (X-subalgebra): reduce(Q(div_a)) == 0 in C_quot."""
    A = Alg(n, quot=True, sX=-1)
    ok = True
    for m in range(maxord + 1):
        for a in multi_indices(n, m):
            div = {}
            for i in range(n):
                b = list(a)
                b[i] += 1
                div[(A.L('X', i, tuple(b)),)] = 1
            qd = A.reduce(A.Q(div)) if False else None
            # compute Q in the full algebra, then reduce
            qfull = {}
            for (lid,), c in div.items():
                qfull = A.padd(qfull, A.Qfull_letter(lid), c)
            r = A.reduce(qfull)
            if r:
                ok = False
    return ok


