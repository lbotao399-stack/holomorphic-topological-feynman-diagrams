"""Closure and divergence on two transverse-linear horizontal fields."""

from mixed_planar import basis, diff, linear, weight, graph_test
from collections import Counter
from functools import cache
from itertools import combinations
from fractions import Fraction


@cache
def states(q, degree, wh, low):
    out = []

    def build(normal, left):
        if len(normal) == q - 2:
            for h in range(low, left - low + 1):
                t = left - h
                for i in range(h + 3):
                    for j in range(t + 3):
                        a = (1, h, i)
                        b = (2, t, j)
                        if a[1:] > b[1:]:
                            continue
                        w = normal + (a, b)
                        if sum(map(weight, w)) == wh:
                            out.append(w)
            return
        for h in range(1, left - 2 * low - (q - 3 - len(normal)) + 1):
            for i in range(h + 3):
                s = (0, h, i)
                if not normal or normal[-1] < s:
                    build(normal + (s,), left - h)

    build((), degree)
    return out


def canon(w):
    # Keep the two transverse labels ordered when taking the exterior sign.
    # Their antisymmetric transverse coefficient makes the planar labels symmetric.
    pure = tuple(s for s in w if s[0] == 0)
    if len(set(pure)) != len(pure):
        return None, 0
    marks = [next(s for s in w if s[0] == n) for n in (1, 2)]
    sign = (-1) ** sum(u > v for i, u in enumerate(w) for v in w[i + 1 :])
    a, b = sorted(s[1:] for s in marks)
    return tuple(sorted(pure)) + ((1, *a), (2, *b)), sign


def double_diff(w):
    out = Counter()
    for i, j in combinations(range(len(w)), 2):
        a, h, u = w[i]
        b, t, v = w[j]
        if a and b:
            continue
        c = u * (t + 2) - v * (h + 2)
        if not c or h + t < -1:
            continue
        new = (a + b, h + t, u + v - 1)
        key, sgn = canon((new,) + tuple(s for n, s in enumerate(w) if n not in (i, j)))
        if sgn:
            out[key] += sgn * (-1) ** (i + j) * c
    return out


def double_raise(w):
    out = Counter()
    for i, (mark, h, j) in enumerate(w):
        if j >= h + 2:
            continue
        key, sgn = canon(w[:i] + ((mark, h, j + 1),) + w[i + 1 :])
        if sgn:
            out[key] += sgn * (h + 2 - j)
    return out


def current_system(conserved):
    X = [("P", w) for w in basis(6, 0)[4] if w[-1][1] >= 0]
    X.extend((k, w) for k, z in (("dx", -1), ("dy", 1)) for w in states(4, 5, z, 0))
    index = {w: i for i, w in enumerate(X)}
    rows = []

    def add(co):
        r = [0] * len(X)
        for k, v in co.items():
            if k in index:
                r[index[k]] += v
        if any(r):
            rows.append(r)

    for w in basis(6, 0)[5]:
        add({("P", u): v for u, v in diff(w).items()})
    for w in basis(6, -2)[4]:
        add({("P", u): v for u, v in linear(w, "raise").items()})
    for k, z in (("dx", -1), ("dy", 1)):
        for w in states(4, 5, z - 2, 0):
            c = {(k, u): v for u, v in double_raise(w).items()}
            if k == "dy":
                c["dx", w] = 1
            add(c)
        for w in states(5, 5, z, -1):
            c = Counter({(k, u): v for u, v in double_diff(w).items()})
            for m in (-2, -1):
                _, h, j = w[m]
                if h != -1:
                    continue
                keep = w[-1 if m == -2 else -2]
                other = (*w[:-2], (1, *keep[1:]))
                # The shear generated by x has vector (0,1), and y gives (-1,0).
                value = (j - 1) if k == "dx" else j
                c["P", other] += value
            add(c)
    for w in states(4, 6, 0, -1) if conserved else ():
        # Differentiating an unmarked horizontal factor on the transverse
        # one-current gives the two symmetrized insertions of P below.
        co = Counter()
        for m in (-2, -1):
            h, i = w[m][1:]
            other = w[-1 if m == -2 else -2]
            if h >= 1:
                raw = (*w[:-2], (0, h, i))
                if len(set(raw)) == len(raw):
                    sign = (-1) ** sum(
                        x > y for z, x in enumerate(raw) for y in raw[z + 1 :]
                    )
                    co["P", (*sorted(raw), (1, *other[1:]))] += sign
        for n, (mark, h, i) in enumerate(w):
            for kind, factor, j in (("dx", i, i - 1), ("dy", h + 2 - i, i)):
                if not factor:
                    continue
                key, sgn = canon(w[:n] + ((mark, h - 1, j),) + w[n + 1 :])
                if sgn:
                    co[kind, key] += sgn * factor
        add(co)
    count = len(rows)
    add({("P", w): v for w, v in graph_test().items()})
    return X, rows[:count], rows[-1]


def rational_solution(X, rows, det):
    from mixed_planar import lead, subtract
    from math import gcd, lcm
    from functools import reduce

    rel = {}
    for r in rows:
        v = {i: Fraction(a) for i, a in enumerate(r) if a}
        key, c = lead(v, rel)
        if key is not None:
            rel[key] = {k: v0 / c for k, v0 in v.items()}

    def rem(v):
        for k in sorted(rel):
            if v.get(k):
                subtract(v, rel[k], v[k])
        return v

    R = rem({i: Fraction(n) for i, n in enumerate(det) if n})
    if not R:
        return len(rel), None, 0
    free = min(R)
    values = {free: Fraction(1)}
    for k in sorted(rel, reverse=True):
        values[k] = -sum(val * values.get(i, 0) for i, val in rel[k].items() if i != k)
    scale = lcm(*(c.denominator for c in values.values()))
    c = [int(values.get(i, 0) * scale) for i in range(len(X))]
    g = reduce(gcd, c)
    c = [i // g for i in c]
    assert all(sum(a * b for a, b in zip(r, c)) == 0 for r in rows)
    return (
        len(rel),
        {(k, w): x for (k, w), x in zip(X, c) if x},
        sum(i * j for i, j in zip(c, det)),
    )


if __name__ == "__main__":
    for conserved in (False, True):
        X, rows, det = current_system(conserved)
        rank, solution, pairing = rational_solution(X, rows, det)
        assert (len(X), len(rows), rank, pairing) == (
            (602, 2027, 601, 0) if conserved else (602, 1571, 600, -665280)
        )
        if solution:
            assert Counter(k for k, w in solution) == {"P": 148, "dx": 222, "dy": 222}
        print(
            "strict divergence",
            conserved,
            "equations",
            len(rows),
            "rank",
            rank,
            "cycle pairing",
            pairing,
        )
