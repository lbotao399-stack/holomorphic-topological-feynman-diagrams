"""Layer c): independent numerical oracle (double precision).  Uses no reduction code.

    K(lam; z) = int_{RP^{N-1}_{>0}} D(t) F(y(t)) exp(-sum_e y_e.z_e) iota_E prod_e dt_e ,   N = |I|.

Scale-invariant density.  For any covector a,  D (a.t) = det[a ; Psi] with Psi the rows (i, r) of
C_re y^i_e; with a_e = 1/t_e,

    S(t) := D(t) prod_e t_e = det[1 ; V] / (N U^H),        V_{(i,r),e} = C_re t_e y^i_e   (T = 0),
    S(t)  = sum_S Pf(A)[S] prod_{e in S} t_e det[1 ; e_S ; V] / (N U^{H+1/2})              (T = 1),

A = -1/2 dM M^{-1} dM.  The currents are obtained from the loop equations M l = -C t y0
(y0: tree solution of the current law), an n x n solve.

Integration rules:
  'lattice' (default)  log coordinates t_e = exp(s_e), s_N = 0:  K = int S(e^s) d^{N-1}s.  The
           integrand is analytic and decays exponentially; the trapezoidal rule on the lattice
           h Z^{N-1} + shift converges exponentially in 1/h.  Lattice points are generated by flood
           fill from the seeds {-m, 0, m}^{N-1} (m ~ 2/h) through the points with
           |S| > tol * max|S|.  The value returned is
           the mean of two runs with shifts 0 and h/2; the error estimate is half their difference
           plus the sum of |S| h^{N-1} over the evaluated points below the threshold divided by
           1 - exp(-h/2), plus a floor 5e-8 |K| (T = 1) or 1e-11 |K| (T = 0).
  'gauss'  conical product Gauss-Jacobi rule on the simplex sum t = 1 (exact for polynomial
           densities, e.g. one loop; slowly convergent otherwise).
  'qmc'    scrambled Sobol points on the simplex (3-4 digits).

Accuracy of 'lattice' with the default (h, tol), measured against exact values
(tests/test_known.py::test_oracle, tests/test_engine.py::test_oracle_T1_slow); relative errors:
    N - 1 = 2:  3e-11 (triangle, C^2),  4e-9 (three parallel edges, T = 1)
    N - 1 = 3:  1e-8  (box, C^3)
    N - 1 = 4:  1e-7  (two-loop fan, C^2),  7e-7 (theta(1,2,2), R x C)
    N - 1 = 6:  1e-4  (three-loop fan on C^2, graphs (A), (B) on C^3; 8e6 evaluations, 30 s),
                2e-4  (theta(1,3,3) on R x C^2; 2e7 evaluations, 2 min)
For N - 1 = 6 the error is dominated by the tails below the threshold; smaller (h, tol) improve
it at the cost of (1/h)^6 log(1/tol)^6 evaluations.  N - 1 > 6: use method='qmc' (2-3 digits).
"""
import itertools
import math

import numpy as np

from .linalg import inverse

__all__ = ["scaled_density_batch", "density_batch", "kernel", "kernel_lattice", "taylor_coefficient"]


class _Setup:
    def __init__(self, G, C=None):
        self.G = G
        tree = G.spanning_tree()
        self.N, self.g = G.ne, G.nv - 1
        B = G.incidence()
        # tree solution of the current law: y0_e = sum_v Y0[e][v] lam_v, zero on the cotree
        BT = [B[e] for e in tree]                               # g x g  (rows: tree edges)
        inv = inverse([list(col) for col in zip(*BT)])          # (B_T^t)^{-1}
        Y0 = np.zeros((self.N, self.g))
        for k, e in enumerate(tree):
            Y0[e, :] = [float(x) for x in inv[k]]
        self.Y0 = Y0
        self.Cf = np.array(G.fundamental_cycles(tree), dtype=float)       # for the loop equations
        self.C = np.array(G.cycle_matrix() if C is None else C, dtype=float)
        self.n = self.C.shape[0]
        self.R = np.random.RandomState(20261120).uniform(0.5, 1.5, size=(2, self.N))


def _wedge_tables(N, a, b):
    A = list(itertools.combinations(range(N), a))
    Bc = list(itertools.combinations(range(N), b))
    out_keys = {key: i for i, key in enumerate(itertools.combinations(range(N), a + b))}
    table = []
    for i, ka in enumerate(A):
        for j, kb in enumerate(Bc):
            if set(ka) & set(kb):
                continue
            inv = sum(1 for x in ka for y in kb if x > y)
            table.append((i, j, out_keys[tuple(sorted(ka + kb))], -1.0 if inv % 2 else 1.0))
    return table, len(out_keys)


def _pfaffian_components(A2, N, n):
    """A2[r][s]: arrays (B, C(N,2)) of the two-forms A_rs.  Returns Pf(A) as (B, C(N,n))."""
    def wedge(f, a, h, b):
        table, size = _wedge_tables(N, a, b)
        out = np.zeros((f.shape[0], size))
        for (i, j, k, s) in table:
            out[:, k] += s * f[:, i] * h[:, j]
        return out

    def pf(idx):
        if len(idx) == 2:
            return A2[idx[0]][idx[1]], 2
        acc = None
        for j in range(1, len(idx)):
            sub, deg = pf(idx[1:j] + idx[j + 1:])
            term = wedge(A2[idx[0]][idx[j]], 2, sub, deg)
            if (j - 1) % 2:
                term = -term
            acc = term if acc is None else acc + term
        return acc, len(idx)

    return pf(list(range(n)))[0]


def scaled_density_batch(G, t, lam, T=0, C=None, powers=None, z=None, _setup=None):
    """S(t) F(y) exp(-sum y.z) with S = D prod_e t_e (invariant under t -> c t), for an array t
    of shape (B, N).  lam: (nv-1) x H array (or None for H = 0); powers: {(e, i): p}; z: N x H."""
    st = _setup or _Setup(G, C)
    t = np.asarray(t, dtype=float)
    Bn, N = t.shape
    t = t / np.exp(np.mean(np.log(t), axis=1))[:, None]
    n, g = st.n, st.g
    lam = np.zeros((g, 0)) if lam is None else np.asarray(lam, dtype=float)
    H = lam.shape[1]
    if n * (H + T) != N - 1:
        raise ValueError("degree mismatch")
    with np.errstate(all="ignore"):
        Mf = np.einsum("re,be,se->brs", st.Cf, t, st.Cf)
        M = np.einsum("re,be,se->brs", st.C, t, st.C)
        bad = ~(np.isfinite(Mf).all(axis=(1, 2)) & np.isfinite(M).all(axis=(1, 2)))
        Uf = np.linalg.det(M) if n else np.ones(Bn)
        bad |= ~np.isfinite(Uf) | (Uf <= 0)
        if n:
            dUf = np.linalg.det(Mf)
            bad |= ~np.isfinite(dUf) | (dUf <= 0)
        if bad.any():
            Mf[bad] = np.eye(n)
            M[bad] = np.eye(n)
            Uf = np.where(bad, 1.0, Uf)
        if H:
            y0 = st.Y0 @ lam                                              # N x H
            rhs = -np.einsum("re,be,ei->bri", st.Cf, t, y0)
            ell = np.linalg.solve(Mf, rhs)                                # B x n x H
            y = y0[None, :, :] + np.einsum("re,bri->bei", st.Cf, ell)     # B x N x H
            V = np.einsum("re,be,bei->bire", st.C, t, y).reshape(Bn, H * n, N)
        else:
            y = np.zeros((Bn, N, 0))
            V = np.zeros((Bn, 0, N))
        ones = np.ones((Bn, 1, N))
        if T == 0:
            S = np.linalg.det(np.concatenate([ones, V], axis=1)) / N / Uf ** H
        elif n % 2:
            S = np.zeros(Bn)
        else:
            Minv = np.linalg.inv(M)
            pairs = list(itertools.combinations(range(N), 2))
            ia = np.array([p[0] for p in pairs])
            ib = np.array([p[1] for p in pairs])
            A2 = [[None] * n for _ in range(n)]
            for r in range(n):
                for s in range(r + 1, n):
                    X = np.einsum("bac,ae,cf->bef", Minv, st.C * st.C[r][None, :], st.C * st.C[s][None, :])
                    X = X * t[:, :, None] * t[:, None, :]                 # t_e t_f A_rs[e, f]
                    A2[r][s] = -0.5 * (X[:, ia, ib] - X[:, ib, ia])
                    A2[s][r] = -A2[r][s]
            S = None
            if n == 2:
                # Jacobi: det[1 ; V ; e_e ; e_f] = det W (u_e v_f - u_f v_e), W = [1 ; V ; R],
                # u, v = last two columns of W^{-1}; R: two fixed generic rows.
                Ah = -0.5 * (X - np.transpose(X, (0, 2, 1)))               # antisymmetric, A_12 t_e t_f
                W = np.concatenate([ones, V, np.broadcast_to(st.R, (Bn, 2, N))], axis=1)
                detW = np.linalg.det(W)
                okW = np.isfinite(detW) & (np.abs(detW) > 1e-200)
                if okW.all():
                    Winv = np.linalg.inv(W)
                    S = detW * np.einsum("be,bef,bf->b", Winv[:, :, N - 2], Ah, Winv[:, :, N - 1])
            if S is None:
                Pf = _pfaffian_components(A2, N, n)                       # includes prod_{e in S} t_e
                S = np.zeros(Bn)
                for k, sub in enumerate(itertools.combinations(range(N), n)):
                    rows = np.zeros((Bn, n, N))
                    for a, e in enumerate(sub):
                        rows[:, a, e] = 1.0
                    S += Pf[:, k] * np.linalg.det(np.concatenate([ones, rows, V], axis=1))
            S = S / N / Uf ** (H + 0.5)
        if powers:
            for (e, i), p in powers.items():
                S = S * y[:, e, i] ** p
        if z is not None:
            S = S * np.exp(-np.einsum("bei,ei->b", y, np.asarray(z, dtype=float)))
        S = np.where(bad | ~np.isfinite(S), 0.0, S)
    return S


def density_batch(G, t, lam, T=0, C=None, powers=None, z=None):
    """D(t) F(y) exp(-sum y.z) for an array t of shape (B, N).
    Note: with powers or z the result is not homogeneous in t; y is scale invariant."""
    t = np.asarray(t, dtype=float)
    return scaled_density_batch(G, t, lam, T, C, powers, z) / np.prod(t, axis=1)


# ---------------------------------------------------------------------- lattice rule in log coordinates

def _lattice_run(G, lam, T, powers, z, h, tol, shift, st, maxpts, chunk, smax):
    N = G.ne
    dim = N - 1
    base = 1 << (62 // max(dim, 1))
    off = base // 2
    kmax = min(off - 2, int(smax / h))

    def F(k):
        out = np.empty(k.shape[0])
        for a in range(0, k.shape[0], chunk):
            s = k[a:a + chunk] * h + shift
            t = np.concatenate([np.exp(s), np.ones((s.shape[0], 1))], axis=1)
            out[a:a + chunk] = scaled_density_batch(G, t, lam, T, None, powers, z, st)
        return out

    def enc(k):
        key = np.zeros(k.shape[0], dtype=np.int64)
        for j in range(dim):
            key = key * base + (k[:, j] + off)
        return key

    steps = np.concatenate([np.eye(dim, dtype=np.int64), -np.eye(dim, dtype=np.int64)])
    # seeds: all lattice points with coordinates in {-m, 0, m}, m ~ 2/h
    mseed = max(1, int(round(2.0 / h)))
    front = np.array(list(itertools.product((-mseed, 0, mseed), repeat=dim)), dtype=np.int64)
    visited = np.unique(enc(front))
    total, fmax, npts, tail = 0.0, 0.0, 0, 0.0
    clipped = False
    while front.shape[0]:
        vals = F(front)
        npts += front.shape[0]
        total += float(vals.sum())
        fmax = max(fmax, float(np.abs(vals).max()))
        above = np.abs(vals) > tol * fmax
        tail += float(np.abs(vals[~above]).sum())
        keep = front[above]
        # points kept on the boundary |k_j| = kmax of the lattice box: neglected tails beyond smax,
        # estimated with the decay length 2 (exponent 1/2)
        onedge = (np.abs(keep) >= kmax).any(axis=1)
        if onedge.any():
            tail += (2.0 / h) * float(np.abs(vals[above][onedge]).sum())
        if keep.shape[0] == 0:
            break
        nb = (keep[:, None, :] + steps[None, :, :]).reshape(-1, dim)
        inside = (np.abs(nb) <= kmax).all(axis=1)
        if not inside.all():
            clipped = True
            nb = nb[inside]
        keys, idx = np.unique(enc(nb), return_index=True)
        nb = nb[idx]
        new = ~np.isin(keys, visited, assume_unique=True)
        front = nb[new]
        visited = np.union1d(visited, keys[new])
        if npts > maxpts:
            raise RuntimeError("lattice rule: more than %d points; increase h or tol" % maxpts)
    hd = h ** dim
    return total * hd, tail * hd, npts, clipped


def kernel_lattice(G, lam, T=0, powers=None, z=None, h=None, tol=None, maxpts=6e7, chunk=200000,
                   smax=45.0, C=None):
    """Trapezoidal rule in log coordinates.  Returns (value, error estimate, info)."""
    dim = G.ne - 1
    if h is None:
        h = {0: 1.0, 1: 0.4, 2: 0.5, 3: 0.6, 4: 0.7, 5: 0.9}.get(dim, 1.0)
    if tol is None:
        tol = {0: 1e-12, 1: 1e-13, 2: 1e-11, 3: 1e-9, 4: 1e-8, 5: 1e-7}.get(dim, 1e-6)
    lamf = None if lam is None else np.asarray(lam, dtype=float)
    st = _Setup(G, C)
    if dim == 0:
        v = float(scaled_density_batch(G, np.ones((1, 1)), lamf, T, None, powers, z, st)[0])
        return v, 0.0, {"points": 1}
    v0, tail0, n0, c0 = _lattice_run(G, lamf, T, powers, z, h, tol, 0.0, st, maxpts, chunk, smax)
    v1, tail1, n1, c1 = _lattice_run(G, lamf, T, powers, z, h, tol, h / 2.0, st, maxpts, chunk, smax)
    val = 0.5 * (v0 + v1)
    # sub-threshold layer times the geometric factor for the slowest decay exp(-s/2); floor from
    # the cancellations in det M at |s| > 30 (double precision)
    err = 0.5 * abs(v0 - v1) + max(tail0, tail1) / (1.0 - math.exp(-h / 2.0))
    err += (5e-8 if T == 1 else 1e-11) * abs(val)
    return val, err, {"points": n0 + n1, "h": h, "tol": tol, "clipped": c0 or c1, "runs": (v0, v1)}


# ---------------------------------------------------------------------- rules on the simplex

def _gauss_jacobi_01(m, alpha):
    from scipy.special import roots_jacobi
    x, w = roots_jacobi(m, alpha, 0.0)
    return (x + 1.0) / 2.0, w / 2.0 ** (alpha + 1.0)


def _collapse(u):
    Bn, dim = u.shape
    t = np.empty((Bn, dim + 1))
    rem = np.ones(Bn)
    for k in range(dim):
        t[:, k] = rem * u[:, k]
        rem = rem * (1.0 - u[:, k])
    t[:, dim] = rem
    return t


def kernel(G, lam, T=0, powers=None, z=None, method="lattice", h=None, tol=None, m=None,
           npoints=2 ** 17, nrep=8, chunk=100000, seed=0, C=None, maxpts=6e7):
    """Numerical K(lam; z) with insertion prod (y^i_e)^p.  Returns (value, error estimate).
    method: 'lattice' (h, tol), 'gauss' (m nodes per direction), 'qmc' (npoints, nrep)."""
    N = G.ne
    dim = N - 1
    lamf = None if lam is None else np.asarray(lam, dtype=float)
    if method == "lattice":
        val, err, _info = kernel_lattice(G, lamf, T, powers, z, h, tol, maxpts=maxpts, C=C)
        return val, err
    st = _Setup(G, C)

    def f(u, wts):
        tot = 0.0
        for a in range(0, u.shape[0], chunk):
            tt = _collapse(u[a:a + chunk])
            d = scaled_density_batch(G, tt, lamf, T, None, powers, z, st) / np.prod(tt, axis=1)
            tot += float(np.sum(wts[a:a + chunk] * d))
        return tot

    if method == "gauss":
        if m is None:
            m = {1: 20, 2: 14, 3: 12, 4: 10, 5: 8, 6: 7}.get(dim, 6)

        def rule(mm):
            nodes = [_gauss_jacobi_01(mm, dim - 1 - k) for k in range(dim)]
            head = max(0, dim - 5)
            gt = np.meshgrid(*[nodes[k][0] for k in range(head, dim)], indexing="ij")
            wt = np.meshgrid(*[nodes[k][1] for k in range(head, dim)], indexing="ij")
            ut = np.stack([x.ravel() for x in gt], axis=1)
            wt = np.prod(np.stack([x.ravel() for x in wt], axis=1), axis=1)
            tot = 0.0
            for idx in itertools.product(range(mm), repeat=head):
                uh = np.array([nodes[k][0][i] for k, i in enumerate(idx)])
                wh = float(np.prod([nodes[k][1][i] for k, i in enumerate(idx)])) if head else 1.0
                u = np.concatenate([np.broadcast_to(uh, (ut.shape[0], head)), ut], axis=1)
                tot += f(u, wh * wt)
            return tot

        val = rule(m)
        return val, abs(val - rule(m - 2))
    if method == "qmc":
        from scipy.stats import qmc
        vals = []
        for rep in range(nrep):
            u = qmc.Sobol(dim, scramble=True, seed=seed + rep).random(npoints)
            v = u * u * (3.0 - 2.0 * u)
            jac = np.prod(6.0 * u * (1.0 - u), axis=1)
            for k in range(dim):
                jac = jac * (1.0 - v[:, k]) ** (dim - 1 - k)
            vals.append(f(v, jac / npoints))
        vals = np.array(vals)
        return float(vals.mean()), float(vals.std(ddof=1) / math.sqrt(nrep))
    raise ValueError("method must be 'lattice', 'gauss' or 'qmc'")


def taylor_coefficient(G, lam, alpha, T=0, **kw):
    """Coefficient of prod z_{e,i}^{alpha[(e,i)]} in K(lam; z):
    (-1)^{|alpha|} / alpha! * int D prod (y^i_e)^{alpha}.  Returns (value, error estimate)."""
    val, err = kernel(G, lam, T, powers=alpha, **kw)
    c = 1.0
    for p in alpha.values():
        c *= (-1.0) ** p / math.factorial(p)
    return c * val, abs(c) * err
